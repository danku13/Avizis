// video-understand: анализ неоднозначных сегментов монтажа (что реально происходит)
import ZAI from 'z-ai-web-dev-sdk'
import fs from 'node:fs'

const CLIPS: Array<[string, string]> = [
  ['A', 'Сегмент «инспектор узла / скраб таймлайна» (после завершения прогона 1). Опиши по секундам: открывается ли панель инспектора узла справа? двигается ли ползунок таймлайна внизу (скраббинг)? меняется ли граф при перемотке? что делает пользователь?'],
  ['B', 'Сегмент «задача 2, авто-режим, запуск». Опиши: печатается ли задача? переключается ли режим решений (ручной → авто)? нажимается ли запуск? что происходит на графу?'],
  ['C', 'Сегмент «успех + авто-развилка». Опиши: узел выполнился? появляется ли развилка/модалка решения? кто выбирает вариант (пользователь кликает или агент решает сам — видно ли авто-решение в журнале)? как растёт граф?'],
  ['D', 'Сегмент «история прогонов» (финал). Опиши: открывается ли панель истории слева? кликаются ли записи истории? переключается ли отображаемый прогон/граф? что в итоге на экране?'],
  ['E', 'Сегмент «завершение прогона 1». Опиши: как выглядит завершение (статус, метрики, журнал)? что видно на графу?'],
]

async function main() {
  const zai = await ZAI.create()
  for (const [id, ask] of CLIPS) {
    const b64 = fs.readFileSync(`/tmp/clip-${id}.mp4`).toString('base64')
    const res = await zai.chat.completions.createVision({
      messages: [
        {
          role: 'user',
          content: [
            { type: 'text', text: `Запись экрана приложения TACG (тёмный UI: сверху тулбар, слева история прогонов, в центре граф вычислений, снизу лента таймлайна и журнал событий).\n${ask}\nОтветь кратко по-русски списком фактов, только то, что реально видно.` },
            { type: 'video_url', video_url: { url: `data:video/mp4;base64,${b64}` } },
          ],
        },
      ] as any,
      thinking: { type: 'disabled' },
    })
    console.log(`\n===== CLIP ${id} =====`)
    console.log(String(res?.choices?.[0]?.message?.content || '').slice(0, 900))
  }
}
main().catch((e) => { console.error('VLM error:', e?.message || e); process.exit(1) })
