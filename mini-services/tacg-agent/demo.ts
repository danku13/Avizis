/** Скриптованные результаты узлов демо-режима */
export function demoOutput(node: GraphNode, task: string, chosen?: { id: string; label: string }): string {
  switch (node.id) {
    case 'n1':
      return `Собраны исходные данные по задаче «${task}». Объём: 2 847 записей за отчётный период. Выявлены проблемы качества: 14 пропусков в поле «дата», 3 дубликата транзакций. Без валидации данные непригодны для анализа.`
    case 'd1':
      return 'Валидация завершена: пропуски восстановлены интерполяцией, дубликаты удалены. Осталось 2 830 корректных записей, покрытие отчётного периода полное. Данные готовы к анализу.'
    case 'n2':
      return 'Анализ выявил 3 кандидата в аномалии: (1) всплеск активности 14.08 — +340% к медиане; (2) нулевая активность 02–03.09; (3) выброс возвратов 22.09 — в 8 раз выше нормы. Каждый кандидат требует содержательной проверки: есть риск ложных срабатываний.'
    case 'b1a':
      return 'Стат. проверка: z-score кандидатов — 4.2 (всплеск 14.08), −5.1 (простой 02–03.09), 3.8 (возвраты 22.09); все значимы при p<0.01. Метод подтверждает статистическую аномальность, но не объясняет природу событий: бизнес-кампания и сбой неотличимы. Двое кандидатов переданы на ручную трактовку.'
    case 'b1b':
      return 'Сверка с бизнес-событиями: 14.08 — старт рекламной кампании (подтверждено планом маркетинга); 02–03.09 — совпадает с окном техобслуживания касс (расписание ops); 22.09 — крупная B2B-отгрузка по контракту. Все три кандидата получили контекст: источник каждого события известен.'
    case 'b2b':
      return 'Кросс-проверка журналов касс и CRM: простой 02–03.09 подтверждён как технический сбой — потеряны 214 транзакций, восстановимы из офлайн-бэкапа. Возвраты 22.09 в пределах договорной нормы для B2B. Всплеск 14.08 согласуется с показателями кампании. Ложных кандидатов: 0, подтверждённых аномалий: 1.'
    case 'b1c':
      return 'Ответ владельца данных: известны два события — маркетинговая кампания 14.08 и B2B-отгрузка 22.09 (объясняют двух кандидатов). Про период 02–03.09 владельцу ничего не известно — требуется техническое расследование. Ожидание ответа заняло 1 рабочий цикл.'
    case 'n3':
      switch (chosen?.id) {
        case 'a':
          return `Итоговый отчёт по задаче «${task}» сформирован по быстрой стратегии. Стат. проверка подтвердила значимость всех 3 кандидатов, но не объяснила их природу: всплеск 14.08 и возвраты 22.09 переданы на ручную трактовку, единственная готовая рекомендация — простой 02–03.09. Путь: развилка → стат. проверка → итог; 3 узла альтернативных веток не реализовано.`
        case 'c':
          return `Итоговый отчёт по задаче «${task}» сформирован с опорой на контекст владельца данных. Два кандидата объяснены известными событиями (кампания 14.08, B2B-отгрузка 22.09); простой 02–03.09 не объяснён — признан технической аномалией и передан на восстановление журналов касс. Путь: развилка → запрос контекста → итог; 3 узла альтернативных веток не реализовано.`
        case 'b':
        default:
          return `Итоговый отчёт по задаче «${task}» сформирован после глубокого расследования. Подтверждены 2 аномалии: технический сбой 02–03.09 (214 транзакций восстановимы из офлайн-бэкапа) и всплеск 14.08 (кампания — учесть в прогнозе). Возвраты 22.09 — норма (B2B-операция), ложное срабатывание отсеяно до итога. Путь: развилка → сверка → кросс-проверка → итог.`
      }
    default:
      return `Результат шага «${node.title}» по задаче «${task}».`
  }
}
